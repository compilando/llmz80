def test_designed_behaviours_reach_the_generated_table(tmp_path: Path):
    project = create_default_project("Brains", TargetPlatform.SPECTRUM, GenreId.MAZE_CHASE)
    project = set_entity_behaviour(project, "enemy", "chase")
    project = add_entity(project, "guard", "enemy", count=1)
    project = set_entity_behaviour(project, "guard", "guard")

    actors = build_actors(project)
    behaviours = {actor.source_id: actor.behaviour for actor in actors}

    assert behaviours["enemy"] == BEHAVIOUR_CHASE
    assert behaviours["guard"] == BEHAVIOUR_GUARD
    output_dir = render_project(project, tmp_path / "build").output_dir
    data = (output_dir / "src" / "game_data.c").read_text()
    assert f"{BEHAVIOUR_CHASE}" in data.split("g_actor_behaviour")[1].split("}")[0]


