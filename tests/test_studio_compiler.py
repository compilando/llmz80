def test_wall_bitmap_matches_the_authored_terrain(tmp_path: Path):
    project = create_default_project("Walls", TargetPlatform.SPECTRUM, GenreId.MAZE_CHASE)

    packed, offsets = tile_bitmaps(project)

    assert len(offsets) == len(project.levels)
    for index, level in enumerate(project.levels):
        bits = []
        for byte in packed[offsets[index]:offsets[index] + (level.width * level.height + 7) // 8]:
            bits.extend((byte >> (7 - position)) & 1 for position in range(8))
        for row in range(level.height):
            for col in range(level.width):
                expected = 1 if level.tiles[row][col] == "#" else 0
                assert bits[row * level.width + col] == expected, (level.id, col, row)


