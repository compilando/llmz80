@pytest.mark.parametrize("platform", list(TargetPlatform))
def test_rendered_project_is_deterministic_and_owned(tmp_path: Path, platform: TargetPlatform):
    project = create_default_project("Commercial Test", platform, GenreId.MAZE_CHASE)
    directory = ProjectStore(tmp_path).create(project)

    first = render_project(project, directory / "build")
    source = first.main_c.read_text(encoding="utf-8")
    second = render_project(project, directory / "build")

    assert second.main_c.read_text(encoding="utf-8") == source
    assert "Generated by LLMZ80 Studio" in source
    assert (directory / "build" / "design" / "game.yml").is_file()
    manifest = json.loads((directory / "build" / "studio_manifest.json").read_text())
    assert manifest["source_of_truth"] == "game.yml"
    assert manifest["target"] == platform.value


def test_target_platform_layers_use_certified_runtime_calls(tmp_path: Path):
    spectrum = create_default_project("ZX", TargetPlatform.SPECTRUM, GenreId.SINGLE_SCREEN_COLLECT)
    cpc = create_default_project("CPC", TargetPlatform.AMSTRAD_CPC, GenreId.SINGLE_SCREEN_COLLECT)

    zx_dir = render_project(spectrum, tmp_path / "zx").output_dir / "src"
    cpc_dir = render_project(cpc, tmp_path / "cpc").output_dir / "src"
    zx_platform = (zx_dir / "platform.c").read_text()
    cpc_platform = (cpc_dir / "platform.c").read_text()

    assert "in_key_pressed(IN_KEY_SCANCODE_q)" in zx_platform
    assert "zx_cls(PAPER_BLACK | INK_WHITE)" in zx_platform
    assert "cpct_disableFirmware();" in cpc_platform
    assert "cpct_scanKeyboard_f();" in cpc_platform
    assert "cpct_waitVSYNC();" in cpc_platform

    # Gameplay rules are shared, so neither platform layer may contain them.
    for platform_source in (zx_platform, cpc_platform):
        assert "score" not in platform_source
        assert "lives" not in platform_source

    engine = (zx_dir / "engine.c").read_text()
    assert engine == (cpc_dir / "engine.c").read_text()
    assert "SCORE_PER_COLLECTIBLE" in engine
    assert "LEVEL_COUNT" in engine


