def test_audio_mask_follows_the_designed_effects(tmp_path: Path):
    project = create_default_project("Sound", TargetPlatform.SPECTRUM, GenreId.MAZE_CHASE)

    # AUDIO_EFFECTS order is start, collect, hit, level, game_over.
    assert audio_mask(set_audio(project, effects=["start"])) == 0b00001
    assert audio_mask(set_audio(project, effects=["hit", "game_over"])) == 0b10100
    assert audio_mask(set_audio(project, effects=[])) == 0

    header = (
        render_project(project, tmp_path / "build").output_dir / "src" / "game_config.h"
    ).read_text()
    assert "#define AUDIO_EFFECT_MASK 7" in header


