def test_levels_receive_distinct_layouts(tmp_path: Path):
    project = create_default_project("Levels", TargetPlatform.SPECTRUM, GenreId.MAZE_CHASE)
    actors = build_actors(project)

    table = spawn_table(project, actors)

    assert len(table) == project.gameplay.level_count
    assert table[0] != table[1] and table[1] != table[2]
    for level_positions in table:
        collectibles = [
            position
            for position, actor in zip(level_positions, actors)
            if actor.kind == CELL_COLLECTIBLE
        ]
        assert len(set(collectibles)) == len(collectibles)


